BEGIN;

CREATE TABLE public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (btrim(name) <> ''),
  email TEXT NOT NULL UNIQUE CHECK (btrim(email) <> '' AND email = lower(btrim(email))),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT,
  code TEXT NOT NULL UNIQUE CHECK (btrim(code) <> ''),
  title TEXT NOT NULL CHECK (btrim(title) <> ''),
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.modules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES public.courses (id) ON DELETE RESTRICT,
  user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT,
  title TEXT NOT NULL CHECK (btrim(title) <> ''),
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.contents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id BIGINT NOT NULL REFERENCES public.modules (id) ON DELETE RESTRICT,
  title TEXT NOT NULL CHECK (btrim(title) <> ''),
  content TEXT NOT NULL CHECK (btrim(content) <> ''),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.user_content_views (
  user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  content_id BIGINT NOT NULL REFERENCES public.contents (id) ON DELETE CASCADE,
  watched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT user_content_views_user_content_unique UNIQUE (user_id, content_id)
);

CREATE INDEX courses_user_id_idx ON public.courses (user_id);
CREATE INDEX modules_course_id_idx ON public.modules (course_id);
CREATE INDEX modules_user_id_idx ON public.modules (user_id);
CREATE INDEX contents_module_id_idx ON public.contents (module_id);
CREATE INDEX user_content_views_content_id_idx ON public.user_content_views (content_id);

-- The unique pair already indexes user_content_views by user_id first.
CREATE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at = clock_timestamp();
  RETURN NEW;
END;
$$;

CREATE TRIGGER users_set_updated_at
BEFORE UPDATE ON public.users
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER courses_set_updated_at
BEFORE UPDATE ON public.courses
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER modules_set_updated_at
BEFORE UPDATE ON public.modules
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER contents_set_updated_at
BEFORE UPDATE ON public.contents
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- No public policies: application access is reserved for the server-only client.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.courses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.modules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_content_views ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.users, public.courses, public.modules,
  public.contents, public.user_content_views FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.users_id_seq, public.courses_id_seq,
  public.modules_id_seq, public.contents_id_seq FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.set_updated_at() FROM PUBLIC, anon, authenticated;

GRANT USAGE ON SCHEMA public TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.users, public.courses,
  public.modules, public.contents, public.user_content_views TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.users_id_seq, public.courses_id_seq,
  public.modules_id_seq, public.contents_id_seq TO service_role;

COMMIT;
