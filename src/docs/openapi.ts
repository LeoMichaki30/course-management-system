function objectSchema(properties: DocumentObject, required: string[], example?: unknown): DocumentObject {
  return { type: "object", additionalProperties: false, properties, required, ...(example === undefined ? {} : { example }) };
}
function entitySchema(properties: DocumentObject, example: unknown): DocumentObject {
  const responseProperties = {
    id: { ...idSchema, readOnly: true },
    ...properties,
    created_at: createdAt,
    updated_at: updatedAt
  };
  return objectSchema(responseProperties, Object.keys(responseProperties), example);
}

