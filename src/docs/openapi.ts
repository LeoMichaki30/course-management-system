function jsonResponse(description: string, schema: unknown, example: unknown, headers?: DocumentObject): DocumentObject {
  return { description, content: { "application/json": { schema, example } }, ...(headers ? { headers } : {}) };
}
function errorResponse(description: string, examples: Record<string, string>): DocumentObject {
  return { description, content: { "application/json": {
    schema: schemaRef("Error"),
    examples: Object.fromEntries(Object.entries(examples).map(([name, error]) => [name, { value: { error } }]))
  } } };
}
function pathParameter(name: string, description: string): DocumentObject {
  return { name, in: "path", required: true, description, schema: schemaRef("BigIntId"), example: "1" };
}
function requestBody(schema: string, example: unknown): DocumentObject {
  return { required: true, content: { "application/json": { schema: schemaRef(schema), example } } };
}

interface CrudDocumentation {
  path: string;
  name: string;
  plural: string;
  createExample: unknown;
  updateExample: unknown;
  responseExample: unknown;
  writeDescription: string;
  deleteDescription: string;
  writeConflicts?: Record<string, string>;
  deleteConflict?: string;
}

function crudPaths(config: CrudDocumentation): Record<string, DocumentObject> {
  const { path, name, plural } = config;
  const tags = [plural];
  const invalidInput = errorResponse("Invalid body or data constraints. JSON must be an object; unknown fields and generated fields are rejected.", {
    invalidData: `${name} data does not satisfy database constraints.`,
    malformedJson: "Request body must contain valid JSON."
  });
  const invalidId = errorResponse("Invalid path ID: expected a positive BIGINT string within the supported range.", { invalidId: `${name} ID must be a positive BIGINT integer.` });
  const notFound = errorResponse(`${name} does not exist.`, { notFound: `${name} not found.` });
  const serverError = errorResponse("Unexpected database or network failure. Internal details are not exposed.", { unexpected: `Unable to complete the ${name.toLowerCase()} operation.` });
  const writeResponses = {
    "400": invalidInput,
    ...(config.writeConflicts ? { "409": errorResponse("Unique value or foreign key conflict.", config.writeConflicts) } : {}),
    "413": responseRef("PayloadTooLarge"),
    "500": serverError
  };
  return {
    [path]: {
      get: {
        tags, operationId: `list${plural}`, summary: `List ${plural.toLowerCase()}`,
        description: "Returns all records ordered by numeric ID ascending. An empty collection returns []. The repository retrieves additional database pages internally; there are no public pagination parameters.",
        responses: { "200": jsonResponse("Records retrieved.", { type: "array", items: schemaRef(name) }, [config.responseExample]), "500": serverError }
      },
      post: {
        tags, operationId: `create${name}`, summary: `Create a ${name.toLowerCase()}`,
        description: `${config.writeDescription} IDs and timestamps are generated by the database; unknown fields are rejected.`,
        requestBody: requestBody(`Create${name}Input`, config.createExample),
        responses: {
          "201": jsonResponse("Record created.", schemaRef(name), config.responseExample, {
            Location: { description: "Relative URL of the created record.", schema: { type: "string" }, example: `${path}/${(config.responseExample as { id: string }).id}` }
          }),
          ...writeResponses
        }
      }
    },
    [`${path}/{id}`]: {
      parameters: [pathParameter("id", `${name} ID.`)],
      get: {
        tags, operationId: `get${name}`, summary: `Get a ${name.toLowerCase()} by ID`,
        responses: { "200": jsonResponse("Record retrieved.", schemaRef(name), config.responseExample), "400": invalidId, "404": notFound, "500": serverError }
      },
      put: {
        tags, operationId: `update${name}`, summary: `Replace a ${name.toLowerCase()}'s editable fields`,
        description: `Full replacement: all editable fields are required. There is no PATCH endpoint. ${config.writeDescription}`,
        requestBody: requestBody(`Update${name}Input`, config.updateExample),
        responses: {
          "200": jsonResponse("Record updated; updated_at is refreshed by the database.", schemaRef(name), { ...(config.responseExample as DocumentObject), ...(config.updateExample as DocumentObject), updated_at: "2026-10-31T12:00:00Z" }),
          ...writeResponses,
          "400": errorResponse("Invalid path ID, body, or database data constraints.", {
            invalidId: `${name} ID must be a positive BIGINT integer.`,
            invalidData: `${name} data does not satisfy database constraints.`,
            malformedJson: "Request body must contain valid JSON."
          }),
          "404": notFound
        }
      },
      delete: {
        tags, operationId: `delete${name}`, summary: `Delete a ${name.toLowerCase()}`,
        description: config.deleteDescription,
        responses: {
          "204": { description: "Record deleted. The response has no body." },
          "400": invalidId, "404": notFound,
          ...(config.deleteConflict ? { "409": errorResponse("Deletion blocked by a foreign key relationship.", { linkedRecords: config.deleteConflict }) } : {}),
          "500": serverError
        }
      }
    }
  };
}

function viewQuery(name: "userId" | "contentId", entity: "User" | "Content"): DocumentObject {
  return {
    get: {
      tags: ["Content Views"], operationId: entity === "User" ? "listUserContentViews" : "listContentViews",
      summary: `List content views by ${entity.toLowerCase()}`,
      description: `Checks that the ${entity.toLowerCase()} exists first. An existing entity without views returns []. Results are ordered by ${entity === "User" ? "content_id" : "user_id"} ascending, with internal database pagination and no public pagination parameters.`,
      parameters: [pathParameter(name, `${entity} ID to filter by.`)],
      responses: {
        "200": jsonResponse("Views retrieved.", { type: "array", items: schemaRef("UserContentView") }, [viewExample]),
        "400": errorResponse("Invalid path ID.", { invalidId: `${entity} ID must be a positive BIGINT integer.` }),
        "404": errorResponse(`${entity} does not exist.`, { notFound: `${entity} not found.` }),
        "500": responseRef("ViewServerError")
      }
    }
  };
}

